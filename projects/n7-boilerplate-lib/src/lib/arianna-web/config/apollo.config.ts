const getTreeBranches = (depth, hasImage = true) => {
  let branchConfig = `
    label
    id
    document_type
    document_classification
  `;
  if (hasImage) {
    branchConfig = `
      label
      id
      img
      document_type
      document_classification
    `;
  }
  const output = [];
  let i;
  let j;
  // open config
  for (i = 0; i < depth; i += 1) {
    output.push(
      i === 0
        ? branchConfig
        : `branches {${branchConfig}`
    );
  }
  // close config
  for (j = 0; j < depth; j += 1) {
    output.push(j === 0 ? '' : '}');
  }

  return output.join('');
};

